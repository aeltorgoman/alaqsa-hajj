-- ════════════════════════════════════════════════════════════
-- رقم الغرفة لا يتكرّر في الدور الواحد
-- ════════════════════════════════════════════════════════════
-- لا شيء كان يمنع غرفتين برقم ١٢١٢ في الطابق ١٢، فيُسنَد حاجٌّ إلى
-- إحداهما ويُبحث عنه في الأخرى. والقاعدة هي الحَكَم: فحصُ الواجهة
-- وحده يسقط أمام نافذتين مفتوحتين أو طلبين متزامنين.
--
-- والموسم جزءٌ من المفتاح: الغرف مُسنَدة إلى موسم (`season_id`)،
-- وموسمٌ جديد يبدأ بأرقام الفندق نفسها. فالتفرّد داخل الموسم
-- والدور معاً، لا في الجدول كلّه.
--
-- ولا تطبيع: فُحصت القاعدة قبل الكتابة — لا فراغات طرفية ولا قيم
-- فارغة ولا `null` في `floor` أو `number`. فالمقارنة على القيم كما
-- هي، بلا `btrim` ولا `lower` يُقحَمان بلا داعٍ ويغيّران المعنى.

-- ═══ فحصٌ سابق: التكرار القائم لا يُحسم تلقائياً ═══
-- الفهرس الفريد يفشل إن وُجد تكرار، ورسالة بوستجرس تذكر صفّاً
-- واحداً. هذا الفحص يسمّيها كلّها ليعالجها المسؤول بنفسه: لا حذف
-- ولا دمج ولا إعادة ترقيم صامتة — الغرفة قد تكون مقصودة.
do $$
declare v_list text;
begin
  select string_agg(format('موسم %s · دور %s · غرفة %s (×%s)', season_id, floor, number, n), E'\n')
    into v_list
    from (select season_id, floor, number, count(*) n
            from public.rooms
           group by season_id, floor, number
          having count(*) > 1) d;

  if v_list is not null then
    raise exception E'توجد أرقام غرف مكرّرة في الدور نفسه، فلا يمكن تفعيل القاعدة قبل معالجتها:\n%\n\nاحذف الغرف الزائدة (الفارغة منها يحذفها النظام مباشرة) ثم أعد تشغيل هذه الهجرة.', v_list
      using errcode = 'P0001';
  end if;
end $$;

-- ═══ القاعدة ═══
create unique index if not exists rooms_season_floor_number_uniq
  on public.rooms (season_id, floor, number);

-- ملاحظة: `create unique index` (لا `constraint`) ليبقى الحذف
-- والإنشاء متكرّرَي التنفيذ بلا أثر، على نهج بقيّة الهجرات.

