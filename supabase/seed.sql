-- بذرةُ التطوير المحلّيّ — **فارغةٌ عن قصد**
-- ════════════════════════════════════════════════════════════
-- يُشغَّل هذا الملفّ بعد الترحيلات في `supabase db reset` محلّياً
-- وحده. وهو فارغ، وفراغُه قرارٌ مُثبَت لا إغفال.
--
-- ── لماذا لا صفَّ واحد هنا ─────────────────────────────────
-- فُحصت الترحيلاتُ السبعةُ والثلاثون، فكلُّ `insert` فيها واحدٌ
-- من ثلاثة، ولا رابع:
--
--   ١) داخل جسد دالّةٍ أو محفّز — لا يُنفَّذ عند الترحيل أصلاً.
--   ٢) حاوية تخزين (`storage.buckets`) — بنيةٌ تحتيّة يملكها
--      الترحيل: `passengers-docs` و`company-assets` بسياساتها.
--   ٣) ردمٌ مشروط يقرأ صفوفاً قائمة — مثل نسخ `logo` و
--      `dashboard_banner` من `company_config` إلى
--      `company_assets` بـ`on conflict do nothing`، وإنشاء
--      «الموسم الأول» إن وُجد حاجٌّ بلا موسم. وكلُّ هذه
--      **لا تفعل شيئاً على قاعدةٍ جديدة**، وهو المقصود.
--
-- فالمخطَّطُ الناتجُ عن `db reset` صالحٌ وكاملٌ بلا صفٍّ واحد.
-- ولا جدولَ مرجعيٍّ ولا صفَّ إعدادٍ مفردٍ تشترطه القاعدة: الموسمُ
-- الأول يُنشئه المستخدم من الواجهة، وأولُ مسؤولٍ من أداة الطوارئ
-- `scripts/seed_first_admin.mjs` — وكلاهما **مسارُ إقلاعٍ مقصود**
-- لا نقصٌ يُسدّ ببذرة.
--
-- ── ما لا يدخل هذا الملفّ أبداً ────────────────────────────
-- ⚠️ لا صفَّ واحداً من قاعدةٍ قائمة — إنتاجاً كانت أو اختباراً:
-- لا حجّاج · لا غرف · لا باصات · لا مواسم · لا ماليّات · لا
-- مستندات · لا مستخدمون · لا جلسات بوابة · لا تنبيهات.
-- نسخُ صفوفٍ حقيقيةٍ إلى المستودع تسريبُ بياناتٍ لا تهيئةُ بيئة،
-- ولو بدت البياناتُ تجريبيّة.
--
-- ⚠️ ولا سرَّ ولا اعتماد: لا كلمة مرور، ولا مفتاح، ولا رمز.
--
-- ⚠️ وخطُّ الأساس (نقطة ٤) **مخطَّطٌ فقط**. فما يُزرع هنا لاحقاً
-- يبقى محلّيّاً بحتاً، ولا يبلغ الإنتاج بحال: `db push` لا يشغّل
-- هذا الملفّ.
--
-- ── متى يُضاف شيء ─────────────────────────────────────────
-- يُضاف صفٌّ هنا إذا — وفقط إذا — عجزت بيئةٌ محلّيةٌ جديدةٌ عن
-- العمل بدونه، ويُذكر البرهانُ في التعليق فوقه. وبيانات
-- الاختبار الموسميّة لها مكانها القائم:
-- `supabase/scripts/seed_test_seasons.sql` — يُشغَّل يدوياً وعن
-- قصد، ولا يُستدعى من هنا.
