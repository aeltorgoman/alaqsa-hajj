-- ============================================================
-- س٥ — حذف الشيفرة المعيبة
-- ============================================================
-- Security Architecture §١٤ (صفّ س٥) · يغلق C1 و H5 نهائياً.
--
-- `public.users` ودوالّها الثلاث هي **نظام الهوية القديم**: كلمات
-- مرور بـ bcrypt في جدول تطبيقيّ، وتحقّق يتمّ في القاعدة، وإنشاء
-- مستخدم بصلاحيات كيفية عبر دالة SECURITY DEFINER. حلّ محلّها منذ
-- س١–س٢: Supabase Auth للهوية، و`user_profiles` للصلاحيات،
-- و`user-admin` للإدارة. ولم يبقَ لها مستدعٍ منذ س٣.
--
-- وس٤ سحبت EXECUTE منها ومنعت كل وصول إلى الجدول. فهذا الترحيل
-- يحوّل المنع إلى **عدم وجود** — وهو الفرق بين بابٍ موصد وبابٍ
-- لا وجود له.
--
-- ⚠️ **بلا CASCADE عن قصد.** الجرد أثبت أن لا مفتاح أجنبيّ ولا
-- عرض ولا محفّز ولا سياسة ولا دالة تعتمد عليها؛ فإن ظهر اعتمادٌ
-- خفيّ فليَسقط الترحيل صائحاً بدل أن يجرف معه ما لا نعرفه.
--
-- المتتالية `users_id_seq` مملوكة لعمود الجدول فتسقط معه تلقائياً،
-- ولا تحتاج ذكراً ولا CASCADE.

drop function if exists public.verify_user(text, text);
drop function if exists public.create_user(text, text, text, jsonb);
drop function if exists public.update_user(integer, text, text, text, jsonb);

/* ستة صفوف تجريبية — قرار س١ المعتمد: بيانات المستخدمين القديمة
   كلها تجريبية ولا تُرحَّل. والمسار الحيّ auth.users + user_profiles
   قائم ومتحقَّق بدخول فعليّ. */
drop table if exists public.users;
