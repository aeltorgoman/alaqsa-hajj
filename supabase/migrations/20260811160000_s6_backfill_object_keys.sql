-- ============================================================
-- س٦ / الخطوة ٢ — تحويل قيم المستندات من رابط إلى مفتاح كائن
-- ============================================================
-- القرار ق٤: القاعدة تحفظ **مفتاح الكائن** لا رابطاً. الرابط الموقّع
-- مؤقّت بطبيعته، والرابط العامّ يموت يوم تصير الحاوية خاصّة — فأيّهما
-- خُزِّن كان دَيناً. والمفتاح ثابت لا يتعلّق بحالة الحاوية.
--
-- آمِنٌ لأن العميل صار يقبل الشكلين منذ الخطوة ١ (`docKey`)، فلا
-- لحظة تكون فيها الشاشة عاجزة عن قراءة ما في العمود.
--
-- الشرط `position(... ) > 0` يجعل الترحيل:
--   • محصوراً — لا يمسّ إلا الروابط العامة لحاويتنا
--   • ومتكرّر التنفيذ بلا أثر — المفاتيح المحوَّلة لا تطابقه ثانيةً
--
-- جرد ما قبل التنفيذ على الإنتاج: ٢٤ قيمة، كلها قابلة للتحويل،
-- ولا واحدة تحمل ترميز نسبة مئوية ولا ذيل استعلام، وكل مفتاح مشتقّ
-- يقابله كائن موجود فعلاً، و٢٤ مفتاحاً متمايزاً بلا تصادم.

do $$
declare
  prefix constant text := '/storage/v1/object/public/passengers-docs/';
  col text;
begin
  foreach col in array array[
    'passport_url','national_id_url','hajj_permit_url',
    'photo_url','contract_url','flight_ticket_url'
  ] loop
    execute format($f$
      update public.passengers
         set %1$I = split_part(substring(%1$I from position(%2$L in %1$I) + length(%2$L)), '?', 1)
       where %1$I is not null
         and position(%2$L in %1$I) > 0
    $f$, col, prefix);
  end loop;
end $$;
