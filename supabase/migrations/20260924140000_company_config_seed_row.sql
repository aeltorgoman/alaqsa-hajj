--
-- `company_config` جدولُ صفٍّ واحد: `id = 1` دائماً. والـ baseline
-- يُنشئ الجدولَ ولا يُدرج فيه صفاً، والقيمُ الافتراضيةُ معرَّفةٌ على
-- الأعمدة لا على الجدول — فالعمود يأخذ افتراضَه عند الإدراج، ولا
-- يُنشئ الافتراضُ صفاً من تلقاء نفسه. فتبقى قاعدةٌ جديدةٌ بجدولٍ
-- فارغ.
--
-- وأثرُ الفراغ صامت: القراءةُ بـ `.single()` على صفر صفٍّ تُخفق،
-- فيرتدّ التطبيقُ إلى هويةٍ عامّة بلا رسالة. ولا سبيلَ إلى إنشاء
-- الصفّ من داخل التطبيق أصلاً — سياساتُ `company_config` تُتيح
-- `select` و`update` فقط، ولا سياسةَ `insert` فيها البتّة.
--
-- ⚠️ لماذا `where not exists` على **الجدول كلِّه** لا `on conflict (id)`
-- وحدَها: `company_profile_public` تقرأ الهويةَ بـ
-- `... from public.company_config c order by c.id limit 1` — أي **أصغرُ
-- معرّفٍ يفوز**. فلو حملت قاعدةٌ صفَّها الحقيقيَّ بمعرّفٍ آخر (2 مثلاً)،
-- لأضاف `on conflict (id) do nothing` صفَّ الافتراضات بـ `id = 1`
-- **بجانبه**، فيسبقه في الترتيب، فتعرض شاشةُ الدخول المجهولةُ هويةً
-- عامّةً بدل هوية الحملة — صامتةً وبرمز خروج صفر. وهو بعينه العطبُ
-- الذي تعالجه هذه الترحيلة. فالشرطُ على خلوّ الجدول يمنع ذلك تماماً.
--
-- وهذه الترحيلةُ تُدرج ولا تُعدِّل: لا `update` ولا `delete` ولا
-- `upsert` يدهس قيمةً قائمة. وإعادةُ تشغيلها لا تفعل شيئاً. ولا تمسّ
-- مخطّطاً ولا سياسةً ولا صلاحيةً ولا دالّة — صفُّ بياناتٍ واحدٍ لا غير.

insert into public.company_config (id)
select 1
 where not exists (select 1 from public.company_config)
on conflict (id) do nothing;

-- شرطان لاحقان يرفعان بوضوح:
do $$
declare
  n_rows int;
  n_one  int;
begin
  select count(*) into n_rows from public.company_config;
  select count(*) into n_one  from public.company_config where id = 1;

  -- (١) لا يجوز أن يخرج هذا الملفُّ وجدولُ الإعداد فارغ.
  if n_rows = 0 then
    raise exception 'company_config: الجدول ما زال فارغاً بعد الترحيلة.'
      using errcode = 'P0001';
  end if;

  -- (٢) الجدولُ غيرُ فارغٍ لكن لا صفَّ بـ id = 1: قاعدةٌ مكسورةٌ
  --     **قبل** هذه الترحيلة — التطبيقُ كلُّه يقرأ `eq("id", 1)`
  --     فلا يرى صفَّها أصلاً. لم نُدرج شيئاً كي لا نُزيح هويتَها،
  --     ونرفع بدل أن نمرّ بصمت.
  if n_one = 0 then
    raise exception 'company_config: يوجد % صفّ(وف) ولا صفَّ بـ id = 1. التطبيق يقرأ id = 1 وحده، فالقاعدة مكسورة قبل هذه الترحيلة. يُصحَّح المعرّف يدوياً ثم تُعاد.', n_rows
      using errcode = 'P0001';
  end if;
end
$$;
