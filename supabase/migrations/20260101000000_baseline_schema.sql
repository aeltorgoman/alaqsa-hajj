create or replace function public.resolve_pilgrim_id(p_doc text, p_day integer, p_month integer, p_year integer)
returns bigint
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_id bigint; v_dob text; v_nums text[]; v_y int; v_m int; v_d int;
begin
  for v_id, v_dob in
    select id, coalesce(dob, '') from passengers
    where trim(coalesce(passport, ''))    = trim(p_doc)
       or trim(coalesce(national_id, '')) = trim(p_doc)
  loop
    v_nums := array_remove(
      regexp_split_to_array(regexp_replace(v_dob, '[^0-9]+', ' ', 'g'), '\s+'), '');
    if array_length(v_nums, 1) = 3 then
      if length(v_nums[1]) = 4 then
        v_y := v_nums[1]::int; v_m := v_nums[2]::int; v_d := v_nums[3]::int;
      else
        v_d := v_nums[1]::int; v_m := v_nums[2]::int; v_y := v_nums[3]::int;
      end if;
      if v_y = p_year and v_m = p_month and v_d = p_day then
        return v_id;
      end if;
    end if;
  end loop;
  return null;
end; $$;

create or replace function public.announcement_audience(p_target_type text, p_target_ids bigint[])
returns table(passenger_id bigint)
language sql
stable
security definer
set search_path to 'public'
as $$
  select p.id from passengers p
  where (
      p.season_id is null
      or p.season_id = (select s.id from seasons s where s.closed_at is null order by s.id desc limit 1)
    )
    and case coalesce(p_target_type, 'all')
          when 'bus'        then p.bus_id        = any(p_target_ids)
          when 'camp_mina'  then p.camp_mina_id  = any(p_target_ids)
          when 'camp_arafa' then p.camp_arafa_id = any(p_target_ids)
          when 'custom'     then p.id            = any(p_target_ids)
          else true
        end;
$$;

create or replace function public.push_enabled_passengers()
returns table(passenger_id bigint, devices bigint)
language sql
