create or replace function public.verify_user(p_username text, p_password text)
returns table(id bigint, name text, username text, password text, permissions jsonb)
language sql
security definer
as $$
  SELECT id, name, username, password, permissions
  FROM users
  WHERE username = p_username
  AND password = crypt(p_password, password);
$$;

create or replace function public.create_user(p_name text, p_username text, p_password text, p_permissions jsonb)
returns void
language plpgsql
security definer
as $$
BEGIN
  INSERT INTO users (name, username, password, permissions)
  VALUES (p_name, p_username, crypt(p_password, gen_salt('bf')), p_permissions);
END;
$$;

create or replace function public.update_user(p_id integer, p_name text, p_username text, p_password text, p_permissions jsonb)
