-- آخر ما تبقّى من س٦: الحاوية كانت `public=true` وسياستها
-- `Public read` مفتوحة لـ`public` — أي أن كل جواز وبطاقة وتصريح
-- كان يُقرأ برابط مباشر بلا هوية، لمن عرف المفتاح أو خمّنه.
--
-- ولم يكن يجوز إغلاقها قبل اليوم: كل قارئ كان يبني الرابط بنفسه.
-- والآن مرّ كلٌّ من المسارين بطبقته:
--   الموظّف  → createSignedUrl (DocImage · downloadFile · واتساب)
--   الحاجّ   → pilgrim-doc بمفتاح الخدمة، بلا مفاتيح ولا JWT
--
-- ⚠️ الترتيب هنا **مُلزِم ولا يجوز تبديله**: إنشاء رابط موقّع
-- يتطلّب SELECT على الكائن، والسياسة القديمة كانت تخدم الموظّف
-- والمجهول معاً. فإسقاطها بلا بديل يقطع عن الموظّف كل قراءة —
-- العرض والتحميل وروابط واتساب. البديل أولاً، ثم الإسقاط، ثم
-- الخصخصة؛ فلا توجد لحظة واحدة بلا قارئ مخوَّل.
--
-- وأُثبت بالبروفة قبل التطبيق (تغييرات ← قياس ← تراجع كامل):
--   authenticated يقرأ ١٥٠ كائناً · anon يقرأ صفراً · public = f
--
-- `company-assets` خارج هذا الترحيل تماماً: الشعار والخلفية
-- عامّان بطبيعتهما، تعرضهما شاشة الدخول لزائر قبل وجود جلسة.
-- ولا يُحذف هنا أي كائن — لا اليتيم ولا كائنات `0/`.
--
-- التراجع عند الطوارئ (استعادة الخدمة أولاً، ثم التحقيق):
--   update storage.buckets set public = true where id = 'passengers-docs';
--   create policy "Public read" on storage.objects
--     for select using (bucket_id = 'passengers-docs');

-- ١) البديل أولاً: الموظّف المصادَق يقرأ، وبه يوقّع
create policy "Employees read passenger docs" on storage.objects
  for select to authenticated
  using (bucket_id = 'passengers-docs');

-- ٢) ثم تُسقط القراءة العامة
drop policy "Public read" on storage.objects;

-- ٣) ثم تُخصخص الحاوية: تموت روابط /object/public/ للجميع
update storage.buckets set public = false where id = 'passengers-docs';
